/**
 * @param {typeof rawAddonProviders[number]['id']} addonProviderId
 * @param {Array<FormattedFeature['code']>} [addonFeatures]
 * @param {PriceSystem} [priceSystem] (default: priceSystemEuro)
 */
export function getFullProductAddon(addonProviderId, addonFeatures, priceSystem = priceSystemEuro) {
  const rawAddonProvider = rawAddonProviders.find((addonProvider) => addonProvider.id === addonProviderId);
  return formatAddonProduct(rawAddonProvider, priceSystem, addonFeatures);
}

/**
 * @param {typeof rawAddonProviders[number]['id']} addonProviderId
 * @param {PriceSystem} [priceSystem] (default: priceSystemEuro)
 */
export function getProductAddon(addonProviderId, priceSystem = priceSystemEuro) {
  const { plans, productFeatures } = getFullProductAddon(addonProviderId, null, priceSystem);
  return { plans, productFeatures };
}
